import React from 'react';
import { Sparkles, Check, X, Lightbulb } from 'lucide-react';
import { formatCurrency } from '../../utils/format.js';
import Button from '../common/Button.jsx';
import Badge from '../common/Badge.jsx';

export function AiBudgetSuggestion({
  suggestionData,
  onApply,
  onDismiss
}) {
  if (!suggestionData || !suggestionData.suggestions) {
    if (suggestionData?.reason === 'not_enough_data') {
      return (
        <div className="bg-indigo-50/60 border border-indigo-200 rounded-2xl p-6 text-center space-y-2">
          <Sparkles className="h-6 w-6 text-indigo-500 mx-auto" />
          <h4 className="text-sm font-semibold text-indigo-900">More Financial History Needed</h4>
          <p className="text-xs text-indigo-700 max-w-md mx-auto">
            The AI needs at least one complete calendar month of transaction history to generate realistic, personalized budget targets. Start by logging expenses or importing a bank statement!
          </p>
          <div className="pt-2">
            <Button variant="outline" size="sm" onClick={onDismiss}>
              Dismiss
            </Button>
          </div>
        </div>
      );
    }
    return null;
  }

  const { suggestions, provider = 'heuristic' } = suggestionData;
  const { suggestedMonthlyBudget = 0, categoryLimits = [], tips = [] } = suggestions;

  const providerLabel =
    provider === 'groq'
      ? 'Llama 3.3 70B (Groq)'
      : provider === 'gemini'
      ? 'Gemini 2.5 Flash'
      : 'Deterministic Heuristic (100/90/95 Rule)';

  const providerVariant = provider === 'heuristic' ? 'rule' : 'ai';

  return (
    <div className="bg-gradient-to-br from-indigo-50/80 via-white to-purple-50/50 rounded-2xl border border-indigo-200 shadow-sm p-6 space-y-5">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-indigo-100 pb-4">
        <div>
          <div className="flex items-center gap-2">
            <Sparkles className="h-5 w-5 text-indigo-600" />
            <h3 className="text-base font-bold text-slate-900">AI Budget Recommendation</h3>
          </div>
          <p className="text-xs text-slate-500 mt-0.5">
            Grounded in your verified 3-month spending history with deterministic math constraints
          </p>
        </div>

        <div className="flex items-center gap-2">
          <Badge variant={providerVariant} size="sm">
            Generated by: {providerLabel}
          </Badge>
        </div>
      </div>

      {/* Suggested Monthly Budget Card */}
      <div className="bg-white p-4 rounded-xl border border-indigo-100 shadow-sm flex items-center justify-between">
        <div>
          <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
            Suggested Total Monthly Budget
          </span>
          <p className="text-2xl font-extrabold text-indigo-900">
            {formatCurrency(suggestedMonthlyBudget)}
          </p>
        </div>
        <div className="text-right text-xs text-slate-500">
          <span>Targeting safe savings ceiling</span>
        </div>
      </div>

      {/* Category Limits Table */}
      {categoryLimits.length > 0 && (
        <div>
          <h4 className="text-xs font-bold text-slate-700 uppercase tracking-wider mb-2">
            Recommended Category Limits
          </h4>
          <div className="bg-white rounded-xl border border-slate-200 overflow-hidden divide-y divide-slate-100 text-xs">
            {categoryLimits.map((lim) => (
              <div key={lim.category} className="p-3 flex items-center justify-between gap-3 hover:bg-slate-50/50">
                <div className="flex-1">
                  <span className="font-bold text-slate-900">{lim.category}</span>
                  <p className="text-[11px] text-slate-500 mt-0.5">{lim.reason}</p>
                </div>
                <div className="text-right font-extrabold text-slate-900 text-sm">
                  {formatCurrency(lim.suggestedLimit)}
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Saving Tips */}
      {tips.length > 0 && (
        <div className="space-y-1.5">
          <span className="text-xs font-bold text-slate-700 uppercase tracking-wider flex items-center gap-1.5">
            <Lightbulb className="h-3.5 w-3.5 text-amber-500" /> Actionable Tips
          </span>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
            {tips.map((tip, idx) => (
              <div
                key={idx}
                className="p-2.5 bg-white/90 border border-indigo-100 rounded-lg text-xs text-slate-600 leading-snug"
              >
                • {tip}
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Actions */}
      <div className="flex flex-col sm:flex-row items-center justify-end gap-3 pt-3 border-t border-indigo-100">
        <Button variant="ghost" size="md" onClick={onDismiss} icon={X}>
          Dismiss
        </Button>
        <Button
          variant="primary"
          size="md"
          onClick={() => onApply(suggestions)}
          icon={Check}
          className="shadow-md shadow-indigo-600/20"
        >
          Apply to Form (Requires Save)
        </Button>
      </div>
    </div>
  );
}

export default AiBudgetSuggestion;
